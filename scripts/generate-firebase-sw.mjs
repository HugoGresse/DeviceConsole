import { writeFileSync } from 'node:fs'
import { loadEnv } from 'vite'

const FIREBASE_SDK_VERSION = '12.18.0'
const OUTPUT = new URL('../public/firebase-messaging-sw.js', import.meta.url)

const env = loadEnv(process.env.NODE_ENV ?? 'development', process.cwd(), 'VITE_')

const required = [
  'VITE_API_KEY',
  'VITE_AUTH_DOMAIN',
  'VITE_DATABASE_URL',
  'VITE_PROJECT_ID',
  'VITE_MESSAGING_SENDER_ID',
  'VITE_APPID',
]

const missing = required.filter((key) => !env[key])
if (missing.length > 0) {
  console.error(`Cannot generate the messaging service worker, missing: ${missing.join(', ')}`)
  process.exit(1)
}

const config = {
  apiKey: env.VITE_API_KEY,
  authDomain: env.VITE_AUTH_DOMAIN,
  databaseURL: env.VITE_DATABASE_URL,
  projectId: env.VITE_PROJECT_ID,
  messagingSenderId: env.VITE_MESSAGING_SENDER_ID,
  appId: env.VITE_APPID,
}

writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-firebase-sw.mjs - do not edit.
importScripts('https://www.gstatic.com/firebasejs/${FIREBASE_SDK_VERSION}/firebase-app-compat.js')
importScripts('https://www.gstatic.com/firebasejs/${FIREBASE_SDK_VERSION}/firebase-messaging-compat.js')

firebase.initializeApp(${JSON.stringify(config, null, 2)})

self.addEventListener('notificationclick', (event) => {
  event.notification.close()
  // The FCM backend delivers the target in fcm_options.link, but a cross-host link is not
  // handled by the Firebase JS client SDK, so it is resolved manually here.
  const url = event.notification?.data?.FCM_MSG?.notification?.click_action
  if (!url) return

  event.waitUntil(
    self.clients.matchAll({ type: 'window' }).then((windowClients) => {
      const open = windowClients.find((client) => client.url === url && 'focus' in client)
      return open ? open.focus() : self.clients.openWindow?.(url)
    }),
  )
})

firebase.messaging()
`,
)

console.log('Generated public/firebase-messaging-sw.js')
